def parameter_groups(entries: list[dict] | None = None) -> list[tuple]:
    """`PARAMETER_GROUPS` with each leaf's globs replaced by its registry entries.

    Raises naming every glob that lands in no leaf or in more than one, and
    every entry whose paths land in different leaves.
    """
    entries = help_registry()["parameters"] if entries is None else entries
    leaves = [(g, i) for g, (_, _, group_leaves) in enumerate(PARAMETER_GROUPS)
              for i in range(len(group_leaves))]
    claims: dict[str, list[tuple[int, int]]] = {}
    for g, i in leaves:
        globs = PARAMETER_GROUPS[g][2][i][2]
        for entry in entries:
            for path in entry["paths"]:
                if any(_fnmatchcase(path, glob) for glob in globs):
                    claims.setdefault(path, []).append((g, i))
    problems = []
    for entry in entries:
        for path in entry["paths"]:
            where = claims.get(path, [])
            if len(where) != 1:
                problems.append(f"{path}: claimed by {len(where)} leaves")
        homes = {claims[p][0] for p in entry["paths"] if len(claims.get(p, [])) == 1}
        if len(homes) > 1:
            problems.append(f"{entry['paths']}: one entry split across leaves")
    if problems:
        raise RuntimeError(
            "parameter map grouping (PARAMETER_GROUPS in docs/reference_pages.py):\n"
            + "\n".join(problems))
    out = []
    for g, (heading, lead, group_leaves) in enumerate(PARAMETER_GROUPS):
        filled = []
        for i, (subheading, sublead, _) in enumerate(group_leaves):
            members = [e for e in entries if claims[e["paths"][0]][0] == (g, i)]
            filled.append((subheading, sublead, members))
        out.append((heading, lead, filled))
    return out


def _cell(text: str | None) -> str:
    return "" if text is None else str(text).replace("|", "\\|")


def _parameter_table(members: list[dict]) -> list[str]:
    lines = ["| Path | Parameter | Unit | Default | Typical |",
             "| --- | --- | --- | --- | --- |"]
    for entry in members:
        paths = "<br>".join(f"`{p}`" for p in entry["paths"])
        default = "" if entry["default"] is None else f"`{entry['default']}`"
        lines.append(f"| {paths} | {_cell(entry['title'])} | {_cell(entry['unit'])} "
                     f"| {default} | {_cell(entry['typical'])} |")
    return lines + [""]


def _parameter_definitions(members: list[dict]) -> list[str]:
    lines = []
    for entry in members:
        lines += [entry["title"], f": {entry['description']}", ""]
    return lines


def parameter_map() -> str:
    """The body of `reference/parameters.md`: one table per group, then its definitions."""
    out = [_BANNER.format(source="rietx.help"), ""]
    for heading, lead, leaves in parameter_groups():
        out += [f"## {heading}", "", lead, ""]
        for subheading, sublead, members in leaves:
            if subheading:
                out += [f"### {subheading}", ""]
            if sublead:
                out += [sublead, ""]
            out += _parameter_table(members) + _parameter_definitions(members)
    return "\n".join(out)


#: Generated body file name -> the function that writes it.
BODIES = {
    "parameters.md": parameter_map,
}


def write_bodies(into: _Path = GENERATED_DIR) -> None:
    into.mkdir(exist_ok=True)
    for name, build in BODIES.items():
        (into / name).write_text(build(), encoding="utf-8")
