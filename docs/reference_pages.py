# The new manual's Reference tab, generated from the code that owns each fact
# (WP-1981).  Prose pages are written; tables of names are built (WP-1975
# § F8), so none of these pages can drift from the package.
#
# `docs/docs/conf.py` calls `write_bodies()` at build time.  Each body lands in
# `docs/docs/_generated/`, which Sphinx does not read as a document, and a
# committed page under `reference/` carries the title and answer sentence and
# `{include}`s it.  The tests call the same functions, so they read what the
# build would render without running one.

from fnmatch import fnmatchcase as _fnmatchcase
from pathlib import Path as _Path

from rietx.help import help_registry

GENERATED_DIR = _Path(__file__).resolve().parent / "docs" / "_generated"

#: Banner on every generated body, so a reader of the source knows where to edit.
_BANNER = ("<!-- Generated by docs/reference_pages.py from {source}. Do not edit: "
           "edit the source. -->")


# ----------------------------------------------------------------------
# The parameter map
#
# The grouping is the docs build's, never a field on `HelpEntry`: the GUI
# serves `help_registry()` too (`/api/help`), so a group field there would cost
# a GUI rebuild and buy the GUI nothing.  Schema paths are unchanged.  A group
# is a reading of what a parameter does, so surface roughness, a path under
# `instrument.geometry`, sits with the intensity corrections.
#
# Each leaf claims globs by fnmatch over `PARAMETER_HELP`'s keys.  Every key
# must land in exactly one leaf, and every path of one entry in the same leaf;
# `parameter_groups()` raises otherwise, so a new parameter fails the build
# until someone places it.
# ----------------------------------------------------------------------

